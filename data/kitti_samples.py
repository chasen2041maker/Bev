def parse_calib(text: str = CALIB_000000) -> dict:
    """把 calib 文本解析成 numpy 矩阵：P2 (3 × 4)、R0_rect (3 × 3)、Tr_velo_to_cam (3 × 4)。"""
    import numpy as np
    out = {}
    for line in text.strip().splitlines():
        key, vals = line.split(":", 1)
        arr = np.array([float(v) for v in vals.split()])
        out[key] = arr.reshape(3, 3) if key == "R0_rect" else arr.reshape(3, 4)
    return out
